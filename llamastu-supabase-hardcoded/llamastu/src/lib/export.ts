import type { Material } from "../types"

/* ------------------------------------------------------------------ *
 * Full account export
 *
 * The document handed to these builders is produced by the backend at the
 * moment the export is requested (`GET /export`), so it always reflects the
 * latest saved rows rather than whatever the tab happens to be holding.
 * ------------------------------------------------------------------ */

export type ExportDocument = {
  format: string
  version: number
  generatedAt: string
  generatedFor: { id: string; email: string }
  profile: Record<string, unknown>
  progress: Record<string, unknown>
  materials: Record<string, unknown>[]
  notes: Record<string, unknown>[]
  calendarEvents: Record<string, unknown>[]
  timetable: Record<string, unknown>[]
  quizAttempts: Record<string, unknown>[]
  gameProgress: Record<string, unknown>[]
  studyActivity: Record<string, unknown>[]
  xpTransactions: Record<string, unknown>[]
  achievements: Record<string, unknown>[]
  notifications: Record<string, unknown>[]
  excluded: string[]
}

/** Serialises the export document as pretty-printed JSON. */
export function buildExportJson(document: ExportDocument): string {
  return JSON.stringify(document, null, 2)
}

/**
 * One CSV value. Quotes are doubled and the field is always quoted, which is
 * what makes a value containing a comma, a quote or a newline survive a
 * round-trip through a spreadsheet instead of shifting the columns.
 */
function csvValue(value: unknown): string {
  if (value === null || value === undefined) return '""'
  const raw =
    typeof value === "object" ? JSON.stringify(value) : String(value as string | number | boolean)
  return `"${raw.replace(/"/g, '""')}"`
}

/**
 * Flattens the export into one tabular record set. Each row carries the section
 * it came from, so a single CSV can hold records of different shapes without
 * losing which is which. The header is the union of every row's keys, which
 * keeps the file valid even when sections have different columns.
 */
export function exportRows(document: ExportDocument): Record<string, unknown>[] {
  const rows: Record<string, unknown>[] = [
    { record_type: "profile", ...document.profile },
    { record_type: "progress", ...document.progress },
  ]
  const sections: [string, Record<string, unknown>[]][] = [
    ["material", document.materials],
    ["note", document.notes],
    ["calendar_event", document.calendarEvents],
    ["timetable", document.timetable],
    ["quiz_attempt", document.quizAttempts],
    ["game_progress", document.gameProgress],
    ["study_activity", document.studyActivity],
    ["sp_transaction", document.xpTransactions],
    ["achievement", document.achievements],
    ["notification", document.notifications],
  ]
  for (const [type, items] of sections) {
    for (const item of items) rows.push({ record_type: type, ...item })
  }
  return rows
}

export function buildExportCsv(document: ExportDocument): string {
  const rows = exportRows(document)
  const columns: string[] = []
  for (const row of rows) {
    for (const key of Object.keys(row)) if (!columns.includes(key)) columns.push(key)
  }
  // `record_type` first, everything else alphabetical so the file is stable.
  const ordered = [
    "record_type",
    ...columns.filter((column) => column !== "record_type").sort(),
  ]
  const lines = [ordered.map(csvValue).join(",")]
  for (const row of rows) lines.push(ordered.map((column) => csvValue(row[column])).join(","))
  return lines.join("\r\n")
}

/** A short, human-readable companion note describing what the export contains. */
export function buildExportSummary(document: ExportDocument): string {
  return [
    "Llamastu data export",
    `Generated: ${document.generatedAt}`,
    `Account: ${document.generatedFor.email}`,
    "",
    `Materials: ${document.materials.length}`,
    `Notes (own and shared with you): ${document.notes.length}`,
    `Calendar events: ${document.calendarEvents.length}`,
    `Timetable entries: ${document.timetable.length}`,
    `Quiz attempts: ${document.quizAttempts.length}`,
    `Study activity records: ${document.studyActivity.length}`,
    `SP transactions: ${document.xpTransactions.length}`,
    `Achievements: ${document.achievements.length}`,
    "",
    "Not included:",
    ...document.excluded.map((item) => `- ${item}`),
  ].join("\n")
}

/** Builds a self-contained Markdown study pack from a processed material. */
export function buildStudyPack(material: Material): string {
  const lines: string[] = []
  lines.push(`# ${material.title || material.name}`)
  lines.push("")
  lines.push(`*Generated by Llamastu from ${material.name}*`)
  lines.push(`*Source words: ${material.wordCount} · Challenges: ${material.questions.length}*`)
  lines.push("")

  if (material.summary) {
    lines.push("## Summary")
    lines.push("")
    lines.push(material.summary)
    lines.push("")
  }

  if (material.keyPoints.length) {
    lines.push("## Key points")
    lines.push("")
    material.keyPoints.forEach((point) => lines.push(`- ${point}`))
    lines.push("")
  }

  if (material.objectives.length) {
    lines.push("## Learning objectives")
    lines.push("")
    material.objectives.forEach((objective) => lines.push(`- ${objective}`))
    lines.push("")
  }

  if (material.flashcards.length) {
    lines.push("## Flashcards")
    lines.push("")
    material.flashcards.forEach((card, index) => {
      lines.push(`${index + 1}. **${card.front}**`)
      lines.push(`   - ${card.back}`)
    })
    lines.push("")
  }

  if (material.questions.length) {
    lines.push("## Practice questions")
    lines.push("")
    material.questions.forEach((question, index) => {
      lines.push(`${index + 1}. ${question.question}`)
      question.choices.forEach((choice, choiceIndex) => {
        const marker = choiceIndex === question.answerIndex ? "**(correct)**" : ""
        lines.push(`   - ${String.fromCharCode(65 + choiceIndex)}. ${choice} ${marker}`)
      })
      lines.push(`   - _Why:_ ${question.explanation}`)
      lines.push("")
    })
  }

  if (material.extractedText) {
    lines.push("---")
    lines.push("")
    lines.push("## Extracted source text")
    lines.push("")
    lines.push("```")
    lines.push(material.extractedText.slice(0, 20000))
    lines.push("```")
    lines.push("")
  }

  return lines.join("\n")
}

export function downloadFile(filename: string, content: string, mime = "text/markdown"): void {
  const blob = new Blob([content], { type: `${mime};charset=utf-8` })
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement("a")
  anchor.href = url
  anchor.download = filename
  document.body.appendChild(anchor)
  anchor.click()
  document.body.removeChild(anchor)
  window.setTimeout(() => URL.revokeObjectURL(url), 4000)
}

export function safeFileName(value: string): string {
  return value
    .replace(/[^\w.\-() ]+/g, "_")
    .replace(/\s+/g, "-")
    .slice(0, 80)
}
